#!/usr/bin/env python3
"""Builds the MorvaneOS niri theme: niri's default config with the MorvaneOS look.

    python tools/build.py [path/to/default-config.kdl]

Needs only Python. The argument is niri's default config, from the niri package
(/usr/share/doc/niri/default-config.kdl, the default path). Output goes to config/;
commit it, it's what the package installs.

niri reads ~/.config/niri/config.kdl, and falls back to /etc/niri/config.kdl, which
no package owns, so the package installs the themed default there. Users without
their own config follow package updates; a config of their own replaces it.
"""

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/usr/share/doc/niri/default-config.kdl')

# Keep in step with the window colours in morvane-gtk-theme
PASTEL = '#F4A6C6'
BORDER = '#4A3552'  # a step lighter than the title bars: niri draws it over the wallpaper
URGENT = '#F0506E'
WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

# (text in niri's default config, MorvaneOS replacement, how many times it's there)
REPLACEMENTS = [
	('active-color "#7fc8ff"', f'active-color "{PASTEL}"', 1),  # focus ring
	('active-color "#ffc87f"', f'active-color "{PASTEL}"', 1),  # border, when turned on
	('inactive-color "#505050"', f'inactive-color "{BORDER}"', 2),
	('urgent-color "#9b0000"', f'urgent-color "{URGENT}"', 1),
	(
		'spawn-at-startup "waybar"\n',
		f'spawn-at-startup "waybar"\n\n// MorvaneOS wallpaper\nspawn-at-startup "swaybg" "-i" "{WALLPAPER}" "-m" "fill"\n',
		1,
	),
]


def themed(base: str) -> str:
	for old, new, count in REPLACEMENTS:
		if base.count(old) != count:
			sys.exit(f"niri's default config has changed ({old.strip()!r} isn't there {count} time(s)); update tools/build.py")
		base = base.replace(old, new)
	return '// niri default config with the MorvaneOS look: generated by tools/build.py in morvane-niri-theme.\n\n' + base


def build() -> None:
	if not BASE.is_file():
		sys.exit(f"niri's default config not found: {BASE} (pass the path to default-config.kdl from the niri package)")
	out = ROOT / 'config'
	shutil.rmtree(out, ignore_errors=True)
	out.mkdir()
	(out / 'config.kdl').write_text(themed(BASE.read_text()))
	print('Built the niri config.')


if __name__ == '__main__':
	build()
